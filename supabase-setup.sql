-- 1. Create the songs table
CREATE TABLE IF NOT EXISTS public.songs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    artist TEXT NOT NULL,
    file TEXT NOT NULL,
    cover TEXT NOT NULL,
    lyrics TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.songs ENABLE ROW LEVEL SECURITY;

-- 3. Create policies for public access (allow all users to read, insert, delete)
DROP POLICY IF EXISTS "Public can view songs" ON public.songs;
CREATE POLICY "Public can view songs" ON public.songs
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public can add songs" ON public.songs;
CREATE POLICY "Public can add songs" ON public.songs
    FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Public can delete songs" ON public.songs;
CREATE POLICY "Public can delete songs" ON public.songs
    FOR DELETE USING (true);

-- 4. Create Storage Buckets for MP3 files and Cover images
INSERT INTO storage.buckets (id, name, public)
VALUES ('songs', 'songs', true)
ON CONFLICT (id) DO NOTHING;

INSERT INTO storage.buckets (id, name, public)
VALUES ('covers', 'covers', true)
ON CONFLICT (id) DO NOTHING;

-- 5. Storage policies to allow public uploads and downloads
DROP POLICY IF EXISTS "Public Access Songs" ON storage.objects;
CREATE POLICY "Public Access Songs" ON storage.objects
    FOR SELECT USING (bucket_id IN ('songs', 'covers'));

DROP POLICY IF EXISTS "Public Upload Songs" ON storage.objects;
CREATE POLICY "Public Upload Songs" ON storage.objects
    FOR INSERT WITH CHECK (bucket_id IN ('songs', 'covers'));

DROP POLICY IF EXISTS "Public Delete Songs" ON storage.objects;
CREATE POLICY "Public Delete Songs" ON storage.objects
    FOR DELETE USING (bucket_id IN ('songs', 'covers'));

